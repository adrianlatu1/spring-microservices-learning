package com.watchlist.movieapp.mapper;


import com.watchlist.movieapp.dto.request.WatchListItemRequestDTO;
import com.watchlist.movieapp.dto.response.WatchListItemResponseDTO;
import com.watchlist.movieapp.entity.WatchListItem;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;

@Mapper(componentModel = "spring")
public interface WatchListItemMapper {

    // DTO Request → Entity
    @Mapping(target = "id", ignore = true) //not found in request DTO, generated by DB
    @Mapping(target = "user", ignore = true)
    // not found in request DTO, set in service layer based on authenticated user
    @Mapping(target = "media", ignore = true)
    // not found in request DTO, set in service layer based on mediaId from DTO
    @Mapping(target = "addedAt", ignore = true)
    //not found in request DTO, set in service layer to current timestamp
    WatchListItem toEntity(WatchListItemRequestDTO dto);

    // Entity → DTO Response
    @Mapping(source = "user.id", target = "userId") //
    @Mapping(source = "media.id", target = "mediaId")
    @Mapping(source = "media.title", target = "mediaTitle")
    @Mapping(target = "mediaType", expression = "java(getMediaType(item))")
    WatchListItemResponseDTO toResponseDTO(WatchListItem item);

    default String getMediaType(WatchListItem item) {
        if (item.getMedia() != null) {
            return item.getMedia().getClass().getSimpleName().toUpperCase(); // e.g., "Movie" or "Series"
        } else {
            return null;
        }
    }
}
